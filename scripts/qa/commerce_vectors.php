<?php
declare(strict_types=1);
// Golden vectors for the fee: PHP (the server's function) is the source of truth, the browser copy must match.
//   php scripts/qa/commerce_vectors.php --write   regenerate scripts/qa/fixtures/commerce-vectors.json
//   php scripts/qa/commerce_vectors.php --check   fail if the file is not what the PHP function produces now
require __DIR__ . '/../../server/modules/commerce/fee.php';

$termSets = [
    'default' => commerce_normalize_terms([]),
    'custom' => commerce_normalize_terms(['rate_bps' => 1800, 'bracket_rate_bps' => 1500, 'floor_bps' => 100, 'floor_min_cents' => 50000, 'cap_bps' => 500, 'bracket_threshold_cents' => 1000000]),
];
$vectors = [];
foreach ($termSets as $name => $terms) {
    $percent = [
        'currency' => $terms['currency'], 'ratePercent' => $terms['rate_bps'] / 100, 'bracketRatePercent' => $terms['bracket_rate_bps'] / 100,
        'bracketThresholdCents' => $terms['bracket_threshold_cents'], 'floorPercent' => $terms['floor_bps'] / 100, 'floorMinCents' => $terms['floor_min_cents'],
        'capPercent' => $terms['cap_bps'] / 100, 'mode' => $terms['mode'],
    ];
    foreach ([0, 1000, 1000000, 100000000, 5000000000] as $baseline) {
        foreach ([0.0, 0.5, 0.8, 1.0, 1.2] as $ratio) {
            $awarded = (int) round($baseline * $ratio);
            foreach ([0, 490000000, 900000000] as $trailing) {
                foreach (['MXN', 'USD'] as $currency) {
                    $r = commerce_compute_fee($baseline, $awarded, $trailing, $terms, $currency);
                    $vectors[] = ['terms' => $percent, 'baselineCents' => $baseline, 'awardedCents' => $awarded, 'trailingSavingCents' => $trailing, 'currency' => $currency,
                        'expect' => ['savingCents' => $r['savingCents'], 'ratioFeeCents' => $r['ratioFeeCents'], 'floorCents' => $r['floorCents'], 'capCents' => $r['capCents'], 'feeCents' => $r['feeCents'], 'basis' => $r['basis']]];
                }
            }
        }
    }
}
$json = json_encode(['note' => 'Generated by scripts/qa/commerce_vectors.php from server/modules/commerce/fee.php. Do not edit by hand.', 'vectors' => $vectors], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n";
$file = __DIR__ . '/fixtures/commerce-vectors.json';
if (in_array('--write', $argv, true)) { file_put_contents($file, $json); echo "wrote " . count($vectors) . " vectors\n"; exit(0); }
$current = is_file($file) ? str_replace("\r\n", "\n", (string) file_get_contents($file)) : '';
if ($current !== $json) { echo "FAILED commerce vectors: the file is out of date (run with --write)\n"; exit(1); }
echo "OK commerce vectors: " . count($vectors) . " in sync with the PHP fee\n";
